####
# Runs MongoDB's aggregation command against just one facet pipeline
# 'facet_pipeline' is array of two elements. Element 1 is facet name. Element
# 2 is the set of stages for the pipeline.
####
async def aggregate_facet(collection, facet_pipeline):
    results = []
    async for result in collection.aggregate(facet_pipeline[1]):
        results.append(result)
    return [facet_pipeline[0], results]


####
# Single arg wrapper function for performing aggregation on just one facet
# pipeline
####
async def db_aggregate_wrap(args):
    task = asyncio.create_task(aggregate_facet(args[0], args[1]))
    await task
    # get the result
    value = task.result()
    return value


